def initialize_language_state(default_language: str = DEFAULT_LANGUAGE) -> str:
    """Ensure a supported language is present in session state."""
    if default_language not in SUPPORTED_LANGUAGES:
        raise ValueError(f"Unsupported default language: {default_language}")

    language = st.session_state.get(LANGUAGE_SESSION_KEY)
    if language not in SUPPORTED_LANGUAGES:
        st.session_state[LANGUAGE_SESSION_KEY] = default_language
    return st.session_state[LANGUAGE_SESSION_KEY]


def get_language() -> str:
    """Return the currently active UI language."""
    return initialize_language_state()


def set_language(language: str) -> bool:
    """Set the active language and return whether it changed."""
    if language not in SUPPORTED_LANGUAGES:
        raise ValueError(f"Unsupported language: {language}")

    previous = get_language()
    st.session_state[LANGUAGE_SESSION_KEY] = language
    return previous != language


def get_next_language(language: str | None = None) -> str:
    """Return the alternate language for the current two-language setup."""
    current = language or get_language()
    if current not in SUPPORTED_LANGUAGES:
        current = DEFAULT_LANGUAGE
    return "en" if current == "de" else "de"


def toggle_language() -> str:
    """Switch to the alternate language and return it."""
    next_language = get_next_language()
    set_language(next_language)
    return next_language


def get_language_name(language: str, *, display_language: str | None = None) -> str:
    """Return a localized label for a language code."""
    if language not in SUPPORTED_LANGUAGES:
        raise ValueError(f"Unsupported language: {language}")

    lookup_language = display_language or get_language()
    if lookup_language not in SUPPORTED_LANGUAGES:
        lookup_language = DEFAULT_LANGUAGE

    key = f"language.name.{language}"
    return TRANSLATIONS.get(lookup_language, {}).get(
        key,
        TRANSLATIONS[DEFAULT_LANGUAGE].get(key, language),
    )


def t(key: str, *, language: str | None = None, **kwargs) -> str:
    """Translate a key for the active language with fallback to German."""
    current_language = language or get_language()
    if current_language not in SUPPORTED_LANGUAGES:
        current_language = DEFAULT_LANGUAGE

    template = TRANSLATIONS.get(current_language, {}).get(key)
    if template is None:
        template = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)

    if kwargs:
        return template.format(**kwargs)
    return template
